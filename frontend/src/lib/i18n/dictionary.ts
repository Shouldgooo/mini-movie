export function interpolate(
  template: string,
  vars?: Record<string, string | number>
) {
  if (!vars) {
    return template;
  }

  return Object.entries(vars).reduce(
    (current, [key, value]) => current.replaceAll(`{${key}}`, String(value)),
    template
  );
}
